"""One-time, transactional migration of the project's real SQLite schema/data.

Run from the project directory after setting DATABASE_URL. This script reads
hardware_inventory.db and creates/copies its application tables to PostgreSQL.
It refuses to copy into non-empty destination tables to prevent duplicates.
"""
from __future__ import annotations

import os
import sqlite3
from pathlib import Path

import psycopg
from psycopg import sql

ROOT = Path(__file__).resolve().parent
SQLITE_DB = Path(os.environ.get("SQLITE_DB_PATH", str(ROOT / "hardware_inventory.db")))
DATABASE_URL = os.environ.get("DATABASE_URL")


def pg_ddl(sqlite_ddl: str) -> str:
    """Translate SQLite's identity syntax into PostgreSQL identity syntax."""
    return sqlite_ddl.replace(
        "INTEGER PRIMARY KEY AUTOINCREMENT",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    )


def main() -> None:
    if not DATABASE_URL:
        raise SystemExit("ERROR: Set DATABASE_URL to your Supabase PostgreSQL connection string.")
    if not SQLITE_DB.exists():
        raise SystemExit(f"ERROR: SQLite source database not found: {SQLITE_DB}")

    src = sqlite3.connect(str(SQLITE_DB))
    src.row_factory = sqlite3.Row
    pg = psycopg.connect(DATABASE_URL)
    pg.autocommit = False

    try:
        source_tables = src.execute(
            "SELECT name, sql FROM sqlite_master "
            "WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
        ).fetchall()
        if not source_tables:
            raise RuntimeError("No application tables were found in the source SQLite database.")

        # Create referenced parent table(s) before child tables with foreign keys.
        source_tables = sorted(source_tables, key=lambda row: (row["name"] != "hardware", row["name"]))
        source_names = [row["name"] for row in source_tables]
        print(f"Source database: {SQLITE_DB}")
        print("Source tables: " + ", ".join(source_names))

        with pg.cursor() as cur:
            # Create matching tables from the actual SQLite schema, not an unrelated schema.
            for table in source_tables:
                ddl = table["sql"]
                if not ddl:
                    continue
                cur.execute(pg_ddl(ddl))

            # Fail before copying if any destination table already has records.
            for table_name in source_names:
                cur.execute(sql.SQL("SELECT COUNT(*) FROM {}").format(sql.Identifier(table_name)))
                existing = cur.fetchone()[0]
                if existing:
                    raise RuntimeError(
                        f"Destination table {table_name!r} already has {existing} rows. "
                        "No data was copied. Use an empty Supabase schema or inspect it first."
                    )

            # Confirm the destination's column order/names match the source.
            for table_name in source_names:
                source_columns = [r["name"] for r in src.execute(f'PRAGMA table_info("{table_name}")')]
                cur.execute(
                    "SELECT column_name FROM information_schema.columns "
                    "WHERE table_schema = current_schema() AND table_name = %s "
                    "ORDER BY ordinal_position",
                    (table_name,),
                )
                destination_columns = [r[0] for r in cur.fetchall()]
                if source_columns != destination_columns:
                    raise RuntimeError(
                        f"Column mismatch for {table_name!r}. Source={source_columns}; "
                        f"destination={destination_columns}. No data was copied."
                    )

            counts = {}
            for table_name in source_names:
                rows = src.execute(f'SELECT * FROM "{table_name}"').fetchall()
                columns = [item["name"] for item in src.execute(f'PRAGMA table_info("{table_name}")')]
                counts[table_name] = len(rows)
                if not rows:
                    continue
                insert_stmt = sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
                    sql.Identifier(table_name),
                    sql.SQL(", ").join(sql.Identifier(c) for c in columns),
                    sql.SQL(", ").join(sql.Placeholder() for _ in columns),
                )
                cur.executemany(insert_stmt, [tuple(row[c] for c in columns) for row in rows])

            # Synchronize identity sequences so new rows do not collide with imported IDs.
            for table in source_tables:
                table_name = table["name"]
                pk_rows = src.execute(f'PRAGMA table_info("{table_name}")').fetchall()
                identity_columns = [r["name"] for r in pk_rows if r["pk"] and "AUTOINCREMENT" in (table["sql"] or "").upper()]
                for column in identity_columns:
                    cur.execute(
                        sql.SQL(
                            "SELECT setval(pg_get_serial_sequence(%s, %s), "
                            "COALESCE(MAX({}), 1), MAX({}) IS NOT NULL) FROM {}"
                        ).format(sql.Identifier(column), sql.Identifier(column), sql.Identifier(table_name)),
                        (table_name, column),
                    )

        pg.commit()
        print("\nMigration committed successfully. Row counts:")
        for name, count in counts.items():
            print(f"  {name}: {count}")
        print("\nNext: run verify_supabase_migration.py before starting the app.")
    except Exception:
        pg.rollback()
        raise
    finally:
        src.close()
        pg.close()


if __name__ == "__main__":
    main()
