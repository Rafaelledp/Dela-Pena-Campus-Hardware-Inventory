"""Small SQLite/PostgreSQL compatibility layer for the existing application.

Without DATABASE_URL the app continues using its local SQLite database.
With DATABASE_URL set, database operations use Supabase PostgreSQL through psycopg 3.
"""
from __future__ import annotations

import os
import re
import sqlite3 as _sqlite3

try:
    import psycopg as _psycopg
    from psycopg import IntegrityError as _PgIntegrityError
    _PG_IMPORT_ERROR = None
except ImportError as exc:  # SQLite-only use should not require psycopg at import time.
    _psycopg = None
    _PgIntegrityError = Exception
    _PG_IMPORT_ERROR = exc

Error = (_sqlite3.Error, _psycopg.Error) if _psycopg else _sqlite3.Error
IntegrityError = (_sqlite3.IntegrityError, _PgIntegrityError) if _psycopg else _sqlite3.IntegrityError


def using_postgres() -> bool:
    return bool(os.environ.get("DATABASE_URL"))


def _pg_sql(statement: str) -> str:
    """Translate the small set of SQLite SQL syntax used by this project."""
    statement = statement.replace("?", "%s")
    statement = re.sub(
        r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        statement,
        flags=re.IGNORECASE,
    )
    return statement


class _Cursor:
    def __init__(self, cursor, postgres: bool):
        self._cursor = cursor
        self._postgres = postgres
        self._pragma_rows = None

    @property
    def description(self):
        return self._cursor.description

    @property
    def rowcount(self):
        return self._cursor.rowcount

    def execute(self, statement, parameters=None):
        self._pragma_rows = None
        if self._postgres:
            busy = re.fullmatch(r"\s*PRAGMA\s+busy_timeout\s*=\s*\d+\s*;?\s*", statement, re.I)
            if busy:
                return self
            pragma = re.fullmatch(r"\s*PRAGMA\s+table_info\((\w+)\)\s*;?\s*", statement, re.I)
            if pragma:
                table = pragma.group(1)
                self._cursor.execute(
                    "SELECT ordinal_position - 1, column_name, data_type, "
                    "CASE WHEN is_nullable = 'NO' THEN 1 ELSE 0 END, "
                    "column_default, ordinal_position "
                    "FROM information_schema.columns "
                    "WHERE table_schema = current_schema() AND table_name = %s "
                    "ORDER BY ordinal_position",
                    (table,),
                )
                self._pragma_rows = self._cursor.fetchall()
                return self
            statement = _pg_sql(statement)
        if parameters is None:
            self._cursor.execute(statement)
        else:
            self._cursor.execute(statement, parameters)
        return self

    def executemany(self, statement, seq_of_parameters):
        if self._postgres:
            statement = _pg_sql(statement)
        self._cursor.executemany(statement, seq_of_parameters)
        return self

    def fetchone(self):
        if self._pragma_rows is not None:
            return self._pragma_rows.pop(0) if self._pragma_rows else None
        return self._cursor.fetchone()

    def fetchall(self):
        if self._pragma_rows is not None:
            rows, self._pragma_rows = self._pragma_rows, []
            return rows
        return self._cursor.fetchall()

    def close(self):
        self._cursor.close()


class _Connection:
    def __init__(self, connection, postgres: bool):
        self._connection = connection
        self._postgres = postgres

    def cursor(self):
        return _Cursor(self._connection.cursor(), self._postgres)

    def execute(self, statement, parameters=None):
        cursor = self.cursor()
        return cursor.execute(statement, parameters)

    def commit(self):
        return self._connection.commit()

    def rollback(self):
        return self._connection.rollback()

    def close(self):
        return self._connection.close()

    def __enter__(self):
        self._connection.__enter__()
        return self

    def __exit__(self, exc_type, exc, tb):
        return self._connection.__exit__(exc_type, exc, tb)


def connect(database=None, *args, **kwargs):
    """Connect to PostgreSQL when DATABASE_URL is configured; otherwise SQLite."""
    database_url = os.environ.get("DATABASE_URL")
    if database_url:
        if _psycopg is None:
            raise RuntimeError(
                "DATABASE_URL is set, but psycopg is not installed. "
                "Install dependencies with: python -m pip install -r requirements.txt"
            ) from _PG_IMPORT_ERROR
        # Supabase pooler URLs may require SSL; require it for safety unless explicitly set.
        if "sslmode=" not in database_url:
            separator = "&" if "?" in database_url else "?"
            database_url += f"{separator}sslmode=require"
        connection = _psycopg.connect(database_url)
        return _Connection(connection, postgres=True)
    connection = _sqlite3.connect(database, *args, **kwargs)
    return _Connection(connection, postgres=False)
